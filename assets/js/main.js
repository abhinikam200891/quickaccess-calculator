    function hashString(str) {
        let hash = 0;
        for (let i = 0; i < str.length; i++) {
            hash = ((hash << 5) - hash) + str.charCodeAt(i);
            hash |= 0;
        }
        return Math.abs(hash);
    }

    function hexToRgb(hex) {
        if (!hex || typeof hex !== 'string') return null;
        let c = hex.replace('#', '').trim();
        if (c.length === 3) c = c.split('').map(x => x + x).join('');
        if (c.length !== 6) return null;
        const num = parseInt(c, 16);
        return `${(num >> 16) & 255}, ${(num >> 8) & 255}, ${num & 255}`;
    }

    // Resolves metadata directly from self-describing page objects produced by scan-pages.ps1
    function resolveToolMetadata(input, index = 0) {
        const isObj = input && typeof input === 'object';
        const filepath = (isObj ? (input.file || '') : String(input || '')).trim();
        const basename = filepath.split(/[\\/]/).pop().trim();
        const rawName = basename.replace(/\.html?$/i, '');
        const id = rawName.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || `tool-${index}`;

        // 1. Tool name: from <meta name="tool-name">, <title>, or clean filename
        const name = (isObj && (input.name || input.title))
            ? (input.name || input.title).trim()
            : rawName.replace(/[_\-]+/g, ' ').replace(/\b\w/g, c => c.toUpperCase());

        // 2. Icon: from <meta name="tool-icon"> or clean default
        const icon = (isObj && input.icon) ? input.icon.trim() : '⚡';

        // 3. Description: from <meta name="tool-desc"> or default
        const desc = (isObj && input.desc) ? input.desc.trim() : `${name} module`;

        // 4. Color & theme derived deterministically from tool ID
        const theme = FINTECH_PALETTE[hashString(id) % FINTECH_PALETTE.length];
        const color = theme.color;
        const rgb = theme.rgb;

        return {
            id: id,
            name: name,
            icon: icon,
            file: filepath,
            desc: desc,
            color: color,
            rgb: rgb
        };
    }

